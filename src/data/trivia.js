/** מערבב עותק של מערך (Fisher–Yates) */
export function shuffle(arr) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/**
 * בוחר `n` שאלות לשלב, מעדיף כאלה שטרם נשאלו (`used` — קבוצת מזהים).
 * מחזיר שאלות עם תשובות מעורבבות: { id, q, options, answer, explain, source }.
 */
export function pickQuestions(levelId, n, used = new Set()) {
  const pool = TRIVIA[levelId] || [];
  const fresh = pool.filter(q => !used.has(q.id));
  const rest = pool.filter(q => used.has(q.id));
  const chosen = [...shuffle(fresh), ...shuffle(rest)].slice(0, n);

  return chosen.map(q => {
    const order = shuffle(q.options.map((text, i) => ({ text, correct: i === q.answer })));
    return {
      id: q.id,
      q: q.q,
      options: order.map(o => o.text),
      answer: order.findIndex(o => o.correct),
      explain: q.explain,
      source: q.source,
    };
  });
}
